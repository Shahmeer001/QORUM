"""
SPY Daily Dataset Quality Verification Script (Item 3b / A3).
Checks spy_daily.csv for:
  1. Flat zero-volume bar: Volume == 0
  2. Consecutive identical rows: same OHLCV as the previous row
  3. High < Low (OHLC inversion)
  4. Close outside [Low, High]
  5. Open outside [Low, High]

Writes results to backend/data_cache/data_quality_report.md.
"""
from __future__ import annotations

import sys
from pathlib import Path
import pandas as pd

DATA_PATH = Path("backend/data_cache/spy_daily.csv")
REPORT_PATH = Path("backend/data_cache/data_quality_report.md")


def run_quality_checks(df: pd.DataFrame) -> dict:
    """Run all quality checks and return a dict of findings."""
    findings = {}

    # 1. Zero-volume bars
    zero_vol = df[df["Volume"] == 0]
    findings["zero_volume"] = zero_vol[["dt", "Open", "High", "Low", "Close", "Volume"]].to_dict("records")

    # 2. Consecutive identical rows (same OHLCV as previous row)
    ohlcv_cols = ["Open", "High", "Low", "Close", "Volume"]
    prev = df[ohlcv_cols].shift(1)
    identical = df[(df[ohlcv_cols] == prev).all(axis=1)]
    findings["consecutive_identical"] = identical[["dt"] + ohlcv_cols].to_dict("records")

    # 3. High < Low (OHLC inversion)
    hl_inv = df[df["High"] < df["Low"]]
    findings["high_lt_low"] = hl_inv[["dt", "Open", "High", "Low", "Close"]].to_dict("records")

    # 4. Close outside [Low, High]
    close_out = df[(df["Close"] < df["Low"]) | (df["Close"] > df["High"])]
    findings["close_outside_range"] = close_out[["dt", "Open", "High", "Low", "Close"]].to_dict("records")

    # 5. Open outside [Low, High]
    open_out = df[(df["Open"] < df["Low"]) | (df["Open"] > df["High"])]
    findings["open_outside_range"] = open_out[["dt", "Open", "High", "Low", "Close"]].to_dict("records")

    return findings


def _rows_table(rows: list, cols: list) -> str:
    if not rows:
        return "_None found._\n"
    header = " | ".join(str(c) for c in cols)
    sep = " | ".join("---" for _ in cols)
    lines = [f"| {header} |", f"| {sep} |"]
    for r in rows:
        lines.append("| " + " | ".join(str(r.get(c, "")) for c in cols) + " |")
    return "\n".join(lines) + "\n"


def write_report(findings: dict, df: pd.DataFrame) -> None:
    total = len(df)
    first = df["dt"].iloc[0].strftime("%Y-%m-%d")
    last = df["dt"].iloc[-1].strftime("%Y-%m-%d")

    n_zero = len(findings["zero_volume"])
    n_consec = len(findings["consecutive_identical"])
    n_hl = len(findings["high_lt_low"])
    n_close = len(findings["close_outside_range"])
    n_open = len(findings["open_outside_range"])

    total_issues = n_zero + n_consec + n_hl + n_close + n_open

    def _status(n): return f"**FAIL ({n})**" if n > 0 else "**PASS (0)**"

    ohlcv_cols = ["dt", "Open", "High", "Low", "Close", "Volume"]
    ohlc_cols = ["dt", "Open", "High", "Low", "Close"]

    report = f"""# SPY Data Quality Report
**Dataset**: `{DATA_PATH}`
**Rows**: {total} trading days
**Date Range**: {first} to {last}
**Generated by**: `scripts/validate_spy_data.py` (Item 3b / A3)

---

## Summary

| Check | Result |
| :--- | :--- |
| Zero-volume bars | {_status(n_zero)} |
| Consecutive identical rows (same OHLCV) | {_status(n_consec)} |
| High < Low (OHLC inversion) | {_status(n_hl)} |
| Close outside [Low, High] | {_status(n_close)} |
| Open outside [Low, High] | {_status(n_open)} |
| **Total issues** | **{total_issues}** |

---

## 1. Zero-Volume Bars

{_rows_table(findings["zero_volume"], ohlcv_cols)}

## 2. Consecutive Identical Rows

Rows where all OHLCV values match the previous row (indicates a stale/duplicated bar).

{_rows_table(findings["consecutive_identical"], ohlcv_cols)}

## 3. High < Low (OHLC Inversion)

{_rows_table(findings["high_lt_low"], ohlc_cols)}

## 4. Close outside [Low, High]

{_rows_table(findings["close_outside_range"], ohlc_cols)}

## 5. Open outside [Low, High]

{_rows_table(findings["open_outside_range"], ohlc_cols)}

---

## Notes

- The current file `spy_daily.csv` is the corrected version (SHA-256: `c617dbb50402e607d9a3fa136a5f75b24065f0e772341a7fabb4a2b87211131a`).
- One correction was applied: 2025-05-22 had a stale row (copy of 2025-05-21 with volume 2,169,841). It was replaced with real values from the Nasdaq crosscheck.
- After correction, check 2 (consecutive identical rows) passes because the stale duplicate was removed.
- Findings 2026-04-20: crosscheck shows O=H=L=C=710.14 (placeholder stub); the SPY row is consistent and correct — no correction needed.
"""
    REPORT_PATH.write_text(report, encoding="utf-8")
    print(f"Quality report written to {REPORT_PATH}")
    print(f"Total issues found: {total_issues}")


def main():
    if not DATA_PATH.exists():
        print(f"ERROR: {DATA_PATH} not found", file=sys.stderr)
        sys.exit(1)

    df = pd.read_csv(DATA_PATH)
    df["dt"] = pd.to_datetime(
        df["Date"].astype(str).str.split().str[0], format="%d/%m/%Y"
    )
    df = df.sort_values("dt").reset_index(drop=True)

    findings = run_quality_checks(df)
    write_report(findings, df)

    # Print summary to stdout
    for k, v in findings.items():
        print(f"  {k}: {len(v)} issues")


if __name__ == "__main__":
    main()
